# -*- coding: utf-8 -*-
"""
Application launcher generated by PythonPortableBuilder.

Started by run.cmd / run.ps1 with the bundled runtime\\python.exe. It:
  * resolves every path relative to the distribution root (no build-machine paths),
  * prepares the environment (optional .pth processing, DLL directories, Tcl/Tk),
  * runs the configured entry point (script, module or callable) with the original
    command-line arguments, and propagates the application's exit code.

Configuration lives in launch.json next to this file. Do not edit by hand;
rebuild the package with the toolkit's rebuild.ps1 instead.

Diagnostics: when the environment variable PPB_LAUNCHER_PROBE=1 is set, the
application is NOT started; the launcher prints the arguments it received and
exits with PPB_PROBE_EXIT (default 0). verify.ps1 uses this to test argument
forwarding and exit-code propagation without running application code.
"""

import json
import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(_HERE)

with open(os.path.join(_HERE, "launch.json"), "r", encoding="utf-8") as _fh:
    CONFIG = json.load(_fh)


def _abs(relative):
    return os.path.normpath(os.path.join(ROOT, relative))


def setup_environment():
    """Prepares sys.path and environment. Safe to call more than once."""
    pth_dirs = CONFIG.get("pthDirectories") or []
    if pth_dirs:
        # Some packages (e.g. pywin32) rely on .pth files. The embedded runtime does not
        # run 'import site' automatically, so .pth files are processed explicitly here.
        import site
        for rel in pth_dirs:
            site.addsitedir(_abs(rel))
    for rel in CONFIG.get("dllDirectories") or []:
        path = _abs(rel)
        if os.path.isdir(path) and hasattr(os, "add_dll_directory"):
            os.add_dll_directory(path)
    tcl_root = os.path.join(ROOT, "runtime", "tcl")
    if os.path.isdir(tcl_root):
        for name in os.listdir(tcl_root):
            full = os.path.join(tcl_root, name)
            if name.startswith("tcl") and os.path.isfile(os.path.join(full, "init.tcl")):
                os.environ.setdefault("TCL_LIBRARY", full)
            elif name.startswith("tk") and os.path.isfile(os.path.join(full, "tk.tcl")):
                os.environ.setdefault("TK_LIBRARY", full)
    os.environ["PPB_DIST_ROOT"] = ROOT
    os.environ.setdefault("PPB_APP_ROOT", _abs("app"))
    os.environ.setdefault("PPB_CONFIG_DIR", _abs("config"))
    os.environ.setdefault("PPB_LOG_DIR", _abs("logs"))


def _probe():
    data = {
        "argv": sys.argv[1:],
        "cwd": os.getcwd(),
        "executable": sys.executable,
        "version": "%d.%d.%d" % sys.version_info[:3],
        "root": ROOT,
    }
    sys.stdout.write("PPB_PROBE " + json.dumps(data) + "\n")
    sys.stdout.flush()
    try:
        return int(os.environ.get("PPB_PROBE_EXIT", "0"))
    except ValueError:
        return 0


def main():
    if os.environ.get("PPB_LAUNCHER_PROBE") == "1":
        return _probe()
    setup_environment()
    entry = CONFIG["entry"]
    kind = entry["kind"]
    import runpy

    if kind == "script":
        path = _abs(os.path.join("app", entry["path"]))
        if not os.path.isfile(path):
            sys.stderr.write("Entry script not found: %s\n" % path)
            return 2
        sys.argv[0] = path
        # Same semantics as 'python script.py': the script directory is importable.
        sys.path.insert(0, os.path.dirname(path))
        runpy.run_path(path, run_name="__main__")
        return 0
    if kind == "module":
        sys.argv[0] = entry["module"]
        runpy.run_module(entry["module"], run_name="__main__", alter_sys=True)
        return 0
    if kind == "callable":
        import importlib
        target = importlib.import_module(entry["module"])
        for attr in entry["function"].split("."):
            target = getattr(target, attr)
        sys.argv[0] = CONFIG.get("name") or entry["module"]
        return target()
    sys.stderr.write("Unknown entry point kind: %s\n" % kind)
    return 2


if __name__ == "__main__":
    sys.exit(main())
