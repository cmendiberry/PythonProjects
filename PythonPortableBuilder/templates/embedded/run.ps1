<#
.SYNOPSIS
    {{NAME}} - PowerShell launcher generated by PythonPortableBuilder {{TOOLKIT_VERSION}}.
.DESCRIPTION
    Runs the application with the bundled Python runtime (runtime\{{PYTHON_EXE}}).
    All paths are resolved relative to this script. Arguments are forwarded and
    the application's exit code is returned.

    If script execution is restricted, use run.cmd instead, or run:
        powershell -NoProfile -ExecutionPolicy Bypass -File .\run.ps1 [arguments]
    Files extracted from a downloaded ZIP may need: Unblock-File .\run.ps1
#>
$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$python = Join-Path $root 'runtime\{{PYTHON_EXE}}'
$launcher = Join-Path $root 'launcher\ppb_launch.py'
if (-not (Test-Path -LiteralPath $python)) {
    [Console]::Error.WriteLine("[{{NAME}}] Bundled Python runtime not found: $python")
    exit 9009
}
$env:PPB_CALLER_CWD = (Get-Location -PSProvider FileSystem).ProviderPath
$workingDirectory = '{{WORKING_DIRECTORY}}'
if ($workingDirectory -eq 'app') { Push-Location -LiteralPath (Join-Path $root 'app') }
try {
    if ('{{WINDOWED}}' -eq 'true') {
        # Piping makes PowerShell wait for the windowed (GUI subsystem) interpreter.
        & $python $launcher @args | Out-Default
    } else {
        & $python $launcher @args
    }
    $code = $LASTEXITCODE
} finally {
    if ($workingDirectory -eq 'app') { Pop-Location }
}
exit $code
