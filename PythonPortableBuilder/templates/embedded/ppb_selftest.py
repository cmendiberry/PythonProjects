# -*- coding: utf-8 -*-
"""
Self-test of an embedded distribution generated by PythonPortableBuilder.

Run by verify.ps1 with the BUNDLED interpreter:
    runtime\\python.exe -B launcher\\ppb_selftest.py --report <file.json>

Checks interpreter version/architecture, import paths, dependency imports and
entry-point resolution. Application code is never imported or executed:
entry points are resolved by locating files on sys.path and parsing them.
Third-party dependencies ARE imported (each in its own subprocess).
"""

import argparse
import ast
import json
import os
import struct
import subprocess
import sys
import sysconfig

_HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(_HERE)
sys.path.insert(0, _HERE)
import ppb_launch  # noqa: E402

sys.path.remove(_HERE)

RESULTS = []


def add(name, status, detail=""):
    RESULTS.append({"name": name, "status": status, "detail": detail})


def inside_root(path):
    try:
        p = os.path.normcase(os.path.abspath(path))
        return p == os.path.normcase(ROOT) or p.startswith(os.path.normcase(ROOT) + os.sep)
    except (TypeError, ValueError):
        return False


def find_module_file(module):
    """Locates a module on sys.path WITHOUT importing it (or its parent packages)."""
    parts = module.split(".")
    for base in sys.path:
        if not base or not os.path.isdir(base):
            continue
        candidate = os.path.join(base, *parts)
        if os.path.isfile(os.path.join(candidate, "__init__.py")):
            return os.path.join(candidate, "__init__.py")
        if os.path.isfile(candidate + ".py"):
            return candidate + ".py"
        if os.path.isdir(candidate):
            return candidate  # namespace package
    return None


def defines_name(path, name):
    try:
        with open(path, "r", encoding="utf-8-sig", errors="replace") as fh:
            tree = ast.parse(fh.read(), path)
    except (SyntaxError, OSError) as exc:
        return False, "cannot parse %s: %s" % (path, exc)
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)) and node.name == name:
            return True, ""
        if isinstance(node, ast.Assign):
            for t in node.targets:
                if isinstance(t, ast.Name) and t.id == name:
                    return True, ""
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            for alias in node.names:
                if (alias.asname or alias.name.split(".")[0]) == name:
                    return True, ""
    return False, "'%s' is not defined at module level of %s" % (name, os.path.relpath(path, ROOT))


def import_in_subprocess(module, timeout):
    code = ("import sys; sys.path.insert(0, %r); import ppb_launch; ppb_launch.setup_environment(); "
            "sys.path.remove(%r); import %s" % (_HERE, _HERE, module))
    try:
        proc = subprocess.run([sys.executable, "-B", "-c", code], stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                              timeout=timeout, cwd=ROOT)
    except subprocess.TimeoutExpired:
        return False, "import timed out after %ss" % timeout
    if proc.returncode == 0:
        return True, ""
    err = proc.stderr.decode("utf-8", "replace").strip().splitlines()
    return False, (err[-1] if err else "exit code %d" % proc.returncode)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--report", required=True)
    ap.add_argument("--timeout", type=int, default=120)
    args = ap.parse_args()

    with open(os.path.join(ROOT, "build-manifest.json"), "r", encoding="utf-8-sig") as fh:
        manifest = json.load(fh)
    python = manifest.get("python", {})
    deps = manifest.get("dependencies", {})
    entry = manifest.get("entryPoint", {})

    # 1. interpreter
    actual = "%d.%d.%d" % sys.version_info[:3]
    expected = python.get("version")
    add("python-version", "passed" if actual == expected else "failed", "running %s, expected %s" % (actual, expected))
    plat = sysconfig.get_platform()
    arch = {"win-amd64": "amd64", "win32": "win32", "win-arm64": "arm64"}.get(plat, plat)
    add("python-architecture", "passed" if arch == python.get("architecture") else "failed",
        "%s (%d-bit), expected %s" % (arch, struct.calcsize("P") * 8, python.get("architecture")))
    add("python-executable", "passed" if inside_root(sys.executable) else "failed", sys.executable)

    # 2. import paths
    ppb_launch.setup_environment()
    outside = [p for p in sys.path if p and not inside_root(p)]
    add("import-paths", "failed" if outside else "passed",
        "outside distribution: %s" % outside if outside else "; ".join(os.path.relpath(p, ROOT) for p in sys.path if p))
    expected_paths = [os.path.normcase(os.path.join(ROOT, p)) for p in manifest.get("embedded", {}).get("importPaths", [])]
    missing = [p for p in expected_paths if p not in [os.path.normcase(os.path.abspath(x)) for x in sys.path if x]]
    if missing:
        add("import-paths-configured", "failed", "not on sys.path: %s" % missing)
    else:
        add("import-paths-configured", "passed", "%d configured path(s) present" % len(expected_paths))
    user_site = [p for p in sys.path if "site-packages" in p.lower() and not inside_root(p)]
    add("isolation", "failed" if user_site else "passed",
        "external site-packages on path: %s" % user_site if user_site else "no system or user site-packages")

    # 3. dependency imports (third-party packages only; application code is not imported)
    names = deps.get("importNames") or []
    failures = []
    for n in names:
        ok, detail = import_in_subprocess(n, args.timeout)
        if not ok:
            failures.append("%s (%s)" % (n, detail))
    if not names:
        add("dependency-imports", "skipped", "no third-party packages to import")
    else:
        add("dependency-imports", "failed" if failures else "passed",
            ("; ".join(failures)) if failures else "%d module(s) imported: %s" % (len(names), ", ".join(names)))
    for mod in manifest.get("embedded", {}).get("stdlibChecks", []):
        ok, detail = import_in_subprocess(mod, args.timeout)
        add("stdlib-%s" % mod, "passed" if ok else "failed", detail or "import %s succeeded" % mod)
    if manifest.get("embedded", {}).get("tkinter"):
        code = ("import sys; sys.path.insert(0, %r); import ppb_launch; ppb_launch.setup_environment(); "
                "import tkinter; print(tkinter.Tcl().eval('info patchlevel'))" % _HERE)
        proc = subprocess.run([sys.executable, "-B", "-c", code], stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                              timeout=args.timeout)
        add("tkinter", "passed" if proc.returncode == 0 else "failed",
            ("Tcl " + proc.stdout.decode().strip()) if proc.returncode == 0
            else proc.stderr.decode("utf-8", "replace").strip()[-300:])

    # 4. entry point resolution (static; nothing is executed)
    kind = entry.get("kind")
    if kind == "script":
        path = os.path.join(ROOT, "app", entry.get("path", ""))
        add("entry-point", "passed" if os.path.isfile(path) else "failed", "script app/%s" % entry.get("path"))
    elif kind in ("module", "callable"):
        module = entry.get("module", "")
        f = find_module_file(module)
        if not f:
            add("entry-point", "failed", "module '%s' not found on sys.path" % module)
        elif not inside_root(f):
            add("entry-point", "failed", "module '%s' resolved outside the distribution: %s" % (module, f))
        elif kind == "module" and f.endswith("__init__.py") and not os.path.isfile(
                os.path.join(os.path.dirname(f), "__main__.py")):
            add("entry-point", "failed", "package '%s' has no __main__.py" % module)
        elif kind == "callable":
            ok, detail = defines_name(f, entry.get("function", "").split(".")[0])
            add("entry-point", "passed" if ok else "failed",
                detail or "%s:%s in %s" % (module, entry.get("function"), os.path.relpath(f, ROOT)))
        else:
            add("entry-point", "passed", "module %s -> %s" % (module, os.path.relpath(f, ROOT)))
    else:
        add("entry-point", "failed", "unknown entry point kind %r" % kind)

    with open(args.report, "w", encoding="utf-8") as fh:
        json.dump({"results": RESULTS}, fh, indent=2)
    return 1 if any(r["status"] == "failed" for r in RESULTS) else 0


if __name__ == "__main__":
    sys.exit(main())
