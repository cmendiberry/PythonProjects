#Requires -Version 5.1

<#
.SYNOPSIS
    Verifies this distribution (generated by PythonPortableBuilder) without rebuilding it.

.DESCRIPTION
    Standalone: needs only Windows PowerShell 5.1+ and the files of this distribution.
    It never installs anything and never changes system settings.

    Checks performed (depending on the package type in build-manifest.json):
      * structure and required files
      * SHA-256 checksums (SHA256SUMS) - modified application files are reported as warnings
      * embedded: bundled interpreter version/architecture, import paths, isolation,
        third-party imports, entry-point resolution (ppb_selftest.py)
      * embedded: run.cmd / run.ps1 argument forwarding and exit-code propagation
        (launcher probe mode - application code is NOT executed)
      * executable: PE architecture/subsystem, onedir layout, bundled resources
      * application smoke run ONLY with a safe option that the application itself
        provides (e.g. --help), recorded at build time; credentials-like environment
        variables are removed for that run

.PARAMETER Path
    Distribution root. Defaults to the directory containing this script.
.PARAMETER ReportPath
    Optional path of a JSON report.
.PARAMETER SkipAppRun
    Do not start the application, even with its safe test option.
.PARAMETER SkipChecksums
    Skip SHA-256 verification (faster for very large distributions).
.PARAMETER TimeoutSeconds
    Timeout of each started process.

.EXAMPLE
    powershell -NoProfile -ExecutionPolicy Bypass -File .\verify.ps1
#>
[CmdletBinding()]
param(
    [string]$Path = $PSScriptRoot,
    [string]$ReportPath,
    [switch]$SkipAppRun,
    [switch]$SkipChecksums,
    [ValidateRange(5, 3600)][int]$TimeoutSeconds = 60
)

Set-StrictMode -Version 2.0
$ErrorActionPreference = 'Stop'
$script:Results = New-Object System.Collections.Generic.List[object]
$Path = [System.IO.Path]::GetFullPath($Path).TrimEnd('\')

function Add-Result([string]$Name, [ValidateSet('passed', 'failed', 'warning', 'skipped')][string]$Status, [string]$Detail = '') {
    $script:Results.Add([pscustomobject]@{ name = $Name; status = $Status; detail = $Detail })
    $color = @{ passed = 'Green'; failed = 'Red'; warning = 'Yellow'; skipped = 'DarkGray' }[$Status]
    Write-Host ("  [{0,-7}] {1}{2}" -f $Status, $Name, $(if ($Detail) { " - $Detail" } else { '' })) -ForegroundColor $color
}

function Get-Prop($Object, [string]$Name, $Default = $null) {
    if ($null -eq $Object) { return $Default }
    $p = $Object.PSObject.Properties[$Name]
    if ($p -and $null -ne $p.Value) { return $p.Value }
    return $Default
}

function Quote-Arg([string]$a) {
    if ($a.Length -eq 0) { return '""' }
    if ($a -notmatch '[\s"]') { return $a }
    $sb = New-Object System.Text.StringBuilder; [void]$sb.Append('"'); $bs = 0
    foreach ($ch in $a.ToCharArray()) {
        if ($ch -eq '\') { $bs++; continue }
        if ($ch -eq '"') { [void]$sb.Append('\', $bs * 2 + 1); [void]$sb.Append('"') }
        else { if ($bs) { [void]$sb.Append('\', $bs) }; [void]$sb.Append($ch) }
        $bs = 0
    }
    if ($bs) { [void]$sb.Append('\', $bs * 2) }
    [void]$sb.Append('"'); return $sb.ToString()
}

function Invoke-Checked {
    param([string]$FilePath, [string]$Arguments, [string]$WorkingDirectory, [hashtable]$Environment, [switch]$Scrub)
    $psi = New-Object System.Diagnostics.ProcessStartInfo
    $psi.FileName = $FilePath; $psi.Arguments = $Arguments
    $psi.UseShellExecute = $false; $psi.CreateNoWindow = $true
    $psi.RedirectStandardOutput = $true; $psi.RedirectStandardError = $true; $psi.RedirectStandardInput = $true
    $psi.WorkingDirectory = $(if ($WorkingDirectory) { $WorkingDirectory } else { $Path })
    if ($Scrub) {
        $pattern = '(?i)(^AWS_|^AZURE_|^GOOGLE_|^GCP_|PASSWORD|PASSWD|PWD$|SECRET|TOKEN|CREDENTIAL|API_?KEY|PRIVATE_?KEY|^DATABASE_URL$|^DB_|^PG(HOST|USER|PASSWORD|DATABASE|PORT|PASSFILE|SERVICE|SERVICEFILE)$|^MYSQL_|^MSSQL|^SQLCMD|CONNECTION_?STRING|^ODBC)'
        foreach ($n in @($psi.EnvironmentVariables.Keys)) { if ($n -match $pattern) { $psi.EnvironmentVariables.Remove($n) } }
        $nowhere = Join-Path ([System.IO.Path]::GetTempPath()) 'ppb-validation-no-credentials'
        $psi.EnvironmentVariables['AWS_CONFIG_FILE'] = "$nowhere\config"
        $psi.EnvironmentVariables['AWS_SHARED_CREDENTIALS_FILE'] = "$nowhere\credentials"
        $psi.EnvironmentVariables['AWS_EC2_METADATA_DISABLED'] = 'true'
        $psi.EnvironmentVariables['PGPASSFILE'] = "$nowhere\pgpass"
        $psi.EnvironmentVariables['PPB_VALIDATION_RUN'] = '1'
    }
    if ($Environment) { foreach ($k in $Environment.Keys) { $psi.EnvironmentVariables[$k] = [string]$Environment[$k] } }
    $p = [System.Diagnostics.Process]::Start($psi)
    try { $p.StandardInput.Close() } catch { }
    $out = $p.StandardOutput.ReadToEndAsync(); $err = $p.StandardError.ReadToEndAsync()
    if (-not $p.WaitForExit($TimeoutSeconds * 1000)) {
        try { & taskkill.exe /T /F /PID $p.Id 2>&1 | Out-Null } catch { }
        return [pscustomobject]@{ ExitCode = -1; StdOut = ''; StdErr = "timed out after $TimeoutSeconds s"; TimedOut = $true }
    }
    $p.WaitForExit()
    return [pscustomobject]@{ ExitCode = $p.ExitCode; StdOut = $out.Result; StdErr = $err.Result; TimedOut = $false }
}

function Read-Probe([string]$Text) {
    foreach ($line in ($Text -split "`r?`n")) {
        if ($line.StartsWith('PPB_PROBE ')) { return ($line.Substring(10) | ConvertFrom-Json) }
    }
    return $null
}

function Get-PeInfo([string]$File) {
    $fs = [System.IO.File]::OpenRead($File)
    try {
        $br = New-Object System.IO.BinaryReader $fs
        if ($br.ReadUInt16() -ne 0x5A4D) { return $null }
        $fs.Position = 0x3C; $pe = $br.ReadInt32()
        $fs.Position = $pe; if ($br.ReadUInt32() -ne 0x4550) { return $null }
        $machine = $br.ReadUInt16()
        $fs.Position = $pe + 24 + 68; $subsystem = $br.ReadUInt16()
        $arch = @{ 0x14C = 'win32'; 0x8664 = 'amd64'; 0xAA64 = 'arm64' }[[int]$machine]
        return [pscustomobject]@{ Architecture = $arch; Subsystem = $(if ($subsystem -eq 2) { 'windowed' } elseif ($subsystem -eq 3) { 'console' } else { "$subsystem" }) }
    } finally { $fs.Dispose() }
}

function ConvertFrom-BigEndian([byte[]]$Bytes, [int]$Offset) {
    return ([int64]$Bytes[$Offset] -shl 24) -bor ([int64]$Bytes[$Offset + 1] -shl 16) -bor ([int64]$Bytes[$Offset + 2] -shl 8) -bor [int64]$Bytes[$Offset + 3]
}

# Lists the entries of a PyInstaller onefile archive (CArchive table of contents).
function Get-PyInstallerToc([string]$Exe) {
    $magic = [byte[]](0x4D, 0x45, 0x49, 0x0C, 0x0B, 0x0A, 0x0B, 0x0E)
    $fs = [System.IO.File]::OpenRead($Exe)
    try {
        $len = $fs.Length
        $chunk = [int][Math]::Min($len, 4MB)
        $fs.Position = $len - $chunk
        $buf = New-Object byte[] $chunk
        [void]$fs.Read($buf, 0, $chunk)
        $pos = -1
        for ($i = $chunk - 88; $i -ge 0; $i--) {
            if ($buf[$i] -eq 0x4D -and $buf[$i + 1] -eq 0x45 -and $buf[$i + 2] -eq 0x49 -and $buf[$i + 3] -eq 0x0C) {
                $ok = $true; for ($j = 4; $j -lt 8; $j++) { if ($buf[$i + $j] -ne $magic[$j]) { $ok = $false; break } }
                if ($ok) { $pos = $i; break }
            }
        }
        if ($pos -lt 0) { return $null }
        $pkgLen = ConvertFrom-BigEndian $buf ($pos + 8)
        $tocOff = ConvertFrom-BigEndian $buf ($pos + 12)
        $tocLen = ConvertFrom-BigEndian $buf ($pos + 16)
        $cookieEnd = ($len - $chunk) + $pos + 88
        $start = $cookieEnd - $pkgLen
        $fs.Position = $start + $tocOff
        $toc = New-Object byte[] $tocLen
        [void]$fs.Read($toc, 0, $tocLen)
        $names = New-Object System.Collections.Generic.List[string]
        $o = 0
        while ($o + 18 -le $tocLen) {
            $entryLen = [int](ConvertFrom-BigEndian $toc $o)
            if ($entryLen -le 18) { break }
            $nameBytes = $toc[($o + 18)..($o + $entryLen - 1)]
            $names.Add(([System.Text.Encoding]::UTF8.GetString($nameBytes)).TrimEnd([char]0).Replace('\', '/'))
            $o += $entryLen
        }
        return , $names.ToArray()
    } finally { $fs.Dispose() }
}

# ------------------------------------------------------------------------------
Write-Host "Verifying distribution: $Path" -ForegroundColor Cyan
$manifestPath = Join-Path $Path 'build-manifest.json'
if (-not (Test-Path -LiteralPath $manifestPath)) {
    Add-Result 'manifest' 'failed' 'build-manifest.json not found'
} else {
    $manifest = [System.IO.File]::ReadAllText($manifestPath) | ConvertFrom-Json
    $pkg = $manifest.package
    Add-Result 'manifest' 'passed' ("{0} ({1}{2}), Python {3} [{4}], built {5}" -f $pkg.name, $pkg.type, $(if ($pkg.type -eq 'executable') { "/$($pkg.mode)" } else { '' }), $manifest.python.version, $manifest.python.architecture, $manifest.build.timestampUtc)

    # Structure ----------------------------------------------------------------
    $missing = @(@(Get-Prop $manifest.distribution 'requiredFiles' @()) | Where-Object { -not (Test-Path -LiteralPath (Join-Path $Path $_)) })
    if ($missing.Count) { Add-Result 'structure' 'failed' ("missing: " + ($missing -join ', ')) }
    else { Add-Result 'structure' 'passed' ("{0} required item(s) present" -f @(Get-Prop $manifest.distribution 'requiredFiles' @()).Count) }

    # Checksums ----------------------------------------------------------------
    $sumFile = Join-Path $Path 'SHA256SUMS'
    if ($SkipChecksums) { Add-Result 'checksums' 'skipped' '-SkipChecksums' }
    elseif (-not (Test-Path -LiteralPath $sumFile)) { Add-Result 'checksums' 'warning' 'SHA256SUMS not present' }
    else {
        $bad = @(); $appChanged = @(); $gone = @(); $count = 0
        foreach ($line in [System.IO.File]::ReadAllLines($sumFile)) {
            if ($line -notmatch '^([0-9a-f]{64}) \*(.+)$') { continue }
            $count++
            $rel = $Matches[2]; $expected = $Matches[1]
            $file = Join-Path $Path ($rel.Replace('/', '\'))
            if (-not (Test-Path -LiteralPath $file)) { $gone += $rel; continue }
            $actual = (Get-FileHash -LiteralPath $file -Algorithm SHA256).Hash.ToLowerInvariant()
            if ($actual -ne $expected) { if ($rel.StartsWith('app/')) { $appChanged += $rel } else { $bad += $rel } }
        }
        if ($bad.Count -or $gone.Count) { Add-Result 'checksums' 'failed' ("modified: {0}; missing: {1}" -f (($bad | Select-Object -First 10) -join ', '), (($gone | Select-Object -First 10) -join ', ')) }
        elseif ($appChanged.Count) { Add-Result 'checksums' 'warning' ("{0} application file(s) changed since build (expected after an application update): {1}" -f $appChanged.Count, (($appChanged | Select-Object -First 10) -join ', ')) }
        else { Add-Result 'checksums' 'passed' "$count file(s) match" }
    }

    $safeArgs = @(Get-Prop $manifest.validation 'safeTestArgs' @())

    if ($pkg.type -eq 'embedded') {
        # Interpreter self-test ------------------------------------------------
        $py = Join-Path $Path 'runtime\python.exe'
        if (-not (Test-Path -LiteralPath $py)) { Add-Result 'runtime' 'failed' 'runtime\python.exe missing' }
        else {
            $report = Join-Path ([System.IO.Path]::GetTempPath()) ("ppb-selftest-{0}.json" -f [Guid]::NewGuid().ToString('N'))
            try {
                $r = Invoke-Checked -FilePath $py -Arguments ("-B {0} --report {1} --timeout {2}" -f (Quote-Arg (Join-Path $Path 'launcher\ppb_selftest.py')), (Quote-Arg $report), $TimeoutSeconds)
                if (Test-Path -LiteralPath $report) {
                    $self = [System.IO.File]::ReadAllText($report) | ConvertFrom-Json
                    foreach ($res in $self.results) { Add-Result $res.name $res.status $res.detail }
                } else {
                    Add-Result 'runtime-selftest' 'failed' ("python.exe exit {0}: {1}" -f $r.ExitCode, ($r.StdErr.Trim() -split "`n" | Select-Object -Last 3) -join ' ')
                }
            } finally { if (Test-Path -LiteralPath $report) { Remove-Item -LiteralPath $report -Force } }
        }

        # Launchers ------------------------------------------------------------
        $probeArgs = @('hello world', 'x', '--opt=1')
        $cmd = Join-Path $Path 'run.cmd'
        if (Test-Path -LiteralPath $cmd) {
            $line = '/d /s /c "' + (Quote-Arg $cmd) + ' ' + (($probeArgs | ForEach-Object { Quote-Arg $_ }) -join ' ') + '"'
            $r = Invoke-Checked -FilePath "$env:SystemRoot\System32\cmd.exe" -Arguments $line -WorkingDirectory ([System.IO.Path]::GetTempPath()) -Environment @{ PPB_LAUNCHER_PROBE = '1' }
            $probe = Read-Probe $r.StdOut
            if ($probe -and (@($probe.argv) -join '|') -eq ($probeArgs -join '|')) {
                $exeOk = $probe.executable.StartsWith($Path, [StringComparison]::OrdinalIgnoreCase)
                Add-Result 'launcher-cmd-arguments' $(if ($exeOk) { 'passed' } else { 'failed' }) ("argv={0}; interpreter={1}; cwd={2}" -f ($probe.argv -join ' | '), $probe.executable, $probe.cwd)
            } else { Add-Result 'launcher-cmd-arguments' 'failed' ("unexpected output: {0} {1}" -f $r.StdOut.Trim(), $r.StdErr.Trim()) }
            $r = Invoke-Checked -FilePath "$env:SystemRoot\System32\cmd.exe" -Arguments $line -WorkingDirectory ([System.IO.Path]::GetTempPath()) -Environment @{ PPB_LAUNCHER_PROBE = '1'; PPB_PROBE_EXIT = '7' }
            Add-Result 'launcher-cmd-exit-code' $(if ($r.ExitCode -eq 7) { 'passed' } else { 'failed' }) "expected 7, got $($r.ExitCode)"
        } else { Add-Result 'launcher-cmd' 'failed' 'run.cmd missing' }

        $ps1 = Join-Path $Path 'run.ps1'
        if (Test-Path -LiteralPath $ps1) {
            $psExe = (Get-Process -Id $PID).Path
            $line = '-NoProfile -NonInteractive -ExecutionPolicy Bypass -File ' + (Quote-Arg $ps1) + ' ' + (($probeArgs | ForEach-Object { Quote-Arg $_ }) -join ' ')
            $r = Invoke-Checked -FilePath $psExe -Arguments $line -WorkingDirectory ([System.IO.Path]::GetTempPath()) -Environment @{ PPB_LAUNCHER_PROBE = '1'; PPB_PROBE_EXIT = '5' }
            $probe = Read-Probe $r.StdOut
            $argsOk = $probe -and ((@($probe.argv) -join '|') -eq ($probeArgs -join '|'))
            Add-Result 'launcher-ps1-arguments' $(if ($argsOk) { 'passed' } else { 'failed' }) $(if ($probe) { "argv=" + ($probe.argv -join ' | ') } else { ($r.StdOut + $r.StdErr).Trim() })
            Add-Result 'launcher-ps1-exit-code' $(if ($r.ExitCode -eq 5) { 'passed' } else { 'failed' }) "expected 5, got $($r.ExitCode)"
        } else { Add-Result 'launcher-ps1' 'failed' 'run.ps1 missing' }

        # Application smoke run ------------------------------------------------
        if ($SkipAppRun) { Add-Result 'application-run' 'skipped' '-SkipAppRun' }
        elseif (-not $safeArgs.Count) { Add-Result 'application-run' 'skipped' 'no safe test option is known for this application; application execution was NOT verified' }
        else {
            $line = '/d /s /c "' + (Quote-Arg $cmd) + ' ' + (($safeArgs | ForEach-Object { Quote-Arg $_ }) -join ' ') + '"'
            $r = Invoke-Checked -FilePath "$env:SystemRoot\System32\cmd.exe" -Arguments $line -WorkingDirectory ([System.IO.Path]::GetTempPath()) -Scrub
            $tail = (($r.StdOut + "`n" + $r.StdErr).Trim() -split "`r?`n" | Select-Object -Last 3) -join ' / '
            Add-Result 'application-run' $(if ($r.ExitCode -eq 0) { 'passed' } else { 'failed' }) ("run.cmd {0} -> exit {1}. {2}" -f ($safeArgs -join ' '), $r.ExitCode, $tail)
        }
    } elseif ($pkg.type -eq 'executable') {
        $exe = Join-Path $Path ("{0}.exe" -f $pkg.name)
        if (-not (Test-Path -LiteralPath $exe)) { Add-Result 'executable' 'failed' "$($pkg.name).exe missing" }
        else {
            $pe = Get-PeInfo $exe
            $archOk = $pe -and $pe.Architecture -eq $manifest.python.architecture
            Add-Result 'executable-architecture' $(if ($archOk) { 'passed' } else { 'failed' }) ("{0}, expected {1}" -f $(if ($pe) { $pe.Architecture } else { 'not a PE file' }), $manifest.python.architecture)
            $expectedSub = if ($pkg.windowed) { 'windowed' } else { 'console' }
            if ($pe) { Add-Result 'executable-subsystem' $(if ($pe.Subsystem -eq $expectedSub) { 'passed' } else { 'failed' }) ("{0}, expected {1}" -f $pe.Subsystem, $expectedSub) }

            $resources = @(Get-Prop $manifest 'bundledResources' @())
            if ($pkg.mode -eq 'onedir') {
                $internal = Join-Path $Path '_internal'
                Add-Result 'onedir-layout' $(if (Test-Path -LiteralPath $internal) { 'passed' } else { 'failed' }) '_internal directory'
                $miss = @($resources | Where-Object { -not (Test-Path -LiteralPath (Join-Path $internal ($_.Replace('/', '\')))) })
                if ($resources.Count) { Add-Result 'resources' $(if ($miss.Count) { 'failed' } else { 'passed' }) $(if ($miss.Count) { 'missing: ' + (($miss | Select-Object -First 10) -join ', ') } else { "$($resources.Count) resource file(s) present in _internal" }) }
                else { Add-Result 'resources' 'skipped' 'no resource files declared' }
            } else {
                $toc = $null
                try { $toc = Get-PyInstallerToc $exe } catch { }
                if ($null -eq $toc) { Add-Result 'onefile-archive' 'failed' 'PyInstaller archive not found in executable' }
                else {
                    Add-Result 'onefile-archive' 'passed' "$($toc.Count) archive entries"
                    $set = @{}; foreach ($n in $toc) { $set[$n.ToLowerInvariant()] = $true }
                    $miss = @($resources | Where-Object { -not $set.ContainsKey($_.ToLowerInvariant()) })
                    if ($resources.Count) { Add-Result 'resources' $(if ($miss.Count) { 'failed' } else { 'passed' }) $(if ($miss.Count) { 'missing: ' + (($miss | Select-Object -First 10) -join ', ') } else { "$($resources.Count) resource file(s) embedded" }) }
                    else { Add-Result 'resources' 'skipped' 'no resource files declared' }
                }
            }
            Add-Result 'launcher-arguments' 'skipped' 'native executable: argument forwarding and exit codes are handled by the PyInstaller bootloader (verified only through the application run below)'

            if ($SkipAppRun) { Add-Result 'application-run' 'skipped' '-SkipAppRun' }
            elseif (-not $safeArgs.Count) { Add-Result 'application-run' 'skipped' 'no safe test option is known for this application; application execution was NOT verified' }
            elseif ($pkg.windowed) { Add-Result 'application-run' 'skipped' 'windowed application: not started during validation' }
            else {
                $r = Invoke-Checked -FilePath $exe -Arguments (($safeArgs | ForEach-Object { Quote-Arg $_ }) -join ' ') -WorkingDirectory ([System.IO.Path]::GetTempPath()) -Scrub
                $tail = (($r.StdOut + "`n" + $r.StdErr).Trim() -split "`r?`n" | Select-Object -Last 3) -join ' / '
                Add-Result 'application-run' $(if ($r.ExitCode -eq 0) { 'passed' } else { 'failed' }) ("{0}.exe {1} -> exit {2}. {3}" -f $pkg.name, ($safeArgs -join ' '), $r.ExitCode, $tail)
            }
        }
    } else {
        Add-Result 'package-type' 'failed' "unknown package type '$($pkg.type)'"
    }
}

$failed = @($script:Results | Where-Object { $_.status -eq 'failed' }).Count
$warn = @($script:Results | Where-Object { $_.status -eq 'warning' }).Count
$skipped = @($script:Results | Where-Object { $_.status -eq 'skipped' }).Count
$status = if ($failed) { 'failed' } elseif ($warn) { 'passed-with-warnings' } else { 'passed' }
if ($ReportPath) {
    $report = [ordered]@{ status = $status; timestampUtc = [DateTime]::UtcNow.ToString('o'); distribution = $Path; results = $script:Results.ToArray() }
    [System.IO.File]::WriteAllText($ReportPath, (ConvertTo-Json -InputObject $report -Depth 6), (New-Object System.Text.UTF8Encoding $false))
}
Write-Host ''
Write-Host ("Verification {0}: {1} passed, {2} failed, {3} warning(s), {4} skipped" -f $status.ToUpperInvariant(), @($script:Results | Where-Object { $_.status -eq 'passed' }).Count, $failed, $warn, $skipped) -ForegroundColor $(if ($failed) { 'Red' } elseif ($warn) { 'Yellow' } else { 'Green' })
if ($failed) { exit 3 }
exit 0
